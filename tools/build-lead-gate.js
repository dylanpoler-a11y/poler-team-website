#!/usr/bin/env node
/**
 * build-lead-gate.js — assembles /lead-gate.js (the site-wide 10-second lead
 * gate) from the LISTING page's own sources so the two never drift:
 *
 *   tools/lead-gate.template.js   behaviour (a copy of listing.js's gate logic)
 *   i18n.js                       the gate's EN/ES/PT strings (27 keys)
 *   listing.css                   the gate's CSS (overlay + already-registered)
 *   listing.html                  the country-code <option> list
 *
 * Run after editing any of those:   node tools/build-lead-gate.js
 * Then deploy as usual (npx vercel --prod --yes). Never edit lead-gate.js by hand.
 */
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = (f) => fs.readFileSync(path.join(ROOT, f), 'utf8');

// ── 1. i18n keys the gate uses (must exist in i18n.js in all 3 languages) ──
const KEYS = [
    'leadTitle', 'leadSubtitle', 'step1of2', 'step2of2', 'fullName', 'emailAddress',
    'phonePlaceholder', 'timelineLabel', 'tl0to3', 'tl3to6', 'tl6to12', 'tl12plus',
    'continueBtn', 'consentDisclosure', 'contactTitle', 'contactSubtitle',
    'submitAndContinue', 'submitting', 'errFillAll', 'errInvalidEmail', 'errInvalidPhone',
    'errSelectTimeline', 'errNetwork', 'alreadyRegistered', 'alreadyRegisteredHint',
    'alreadyRegisteredBtn', 'alreadyRegisteredNotFound',
];
const ctx = {
    window: {}, console,
    document: { addEventListener() {}, documentElement: {}, getElementById() { return null; }, querySelectorAll() { return []; } },
    localStorage: { getItem() { return null; }, setItem() {} },
    URLSearchParams,
};
vm.createContext(ctx);
vm.runInContext(read('i18n.js') + ';globalThis.__I18N = I18N;', ctx);
const strings = {};
for (const k of KEYS) {
    const e = ctx.__I18N[k];
    if (!e || !e.en || !e.es || !e.pt) throw new Error(`i18n.js: key "${k}" missing or not trilingual`);
    strings[k] = { en: e.en, es: e.es, pt: e.pt };
}

// ── 2. CSS: the two gate blocks from listing.css + the lock rule ──
const css = read('listing.css');
function slice(startMarker, endMarker) {
    const a = css.indexOf(startMarker);
    const b = css.indexOf(endMarker, a);
    if (a < 0 || b < 0) throw new Error(`listing.css: marker not found (${startMarker} → ${endMarker})`);
    // back up to the start of the comment banner that holds the marker
    const bannerStart = css.lastIndexOf('/* ====', a);
    return css.slice(bannerStart >= 0 ? bannerStart : a, b).trimEnd();
}
const gateCss = slice('LEAD CAPTURE OVERLAY', '/* OTP digit boxes */');
const regCss  = slice('"Already registered?" on the lead gate', '/* ============================================================\n   Recalibration popup');
const LOCK_CSS = `
/* Site-wide lock (lead-gate.js): listing.css blurs #page-wrap; pages without
   one blur every body child except the overlay. Vars below are the listing.css
   values so the gate looks identical on any page, even one with no design tokens. */
#lead-overlay {
    --orange: #1a2744; --orange-dark: #111c33; --navy: #1a2744;
    --text: #1a1a2e; --text-muted: #6b7280; --text-light: #9ca3af;
    --border: #e5e7eb; --border-light: #f3f4f6; --bg: #f7f8fa; --bg-card: #ffffff;
    --font-heading: 'Playfair Display', Georgia, serif;
    --font-body: 'Inter', -apple-system, sans-serif;
    font-family: var(--font-body);
}
:where(#lead-overlay) button { cursor: pointer; font-family: var(--font-body); border: none; background: none; }
:where(#lead-overlay) input, :where(#lead-overlay) select { font-family: var(--font-body); }
:where(#lead-overlay) img { display: block; max-width: 100%; }
html.lead-gate-locked body > :not(#lead-overlay) {
    filter: blur(6px);
    pointer-events: none; user-select: none;
}
.page-wrap.blurred { filter: blur(6px); pointer-events: none; user-select: none; }
`;
const fullCss = [gateCss, regCss, LOCK_CSS].join('\n\n');

// ── 3. Country-code options from listing.html ──
const html = read('listing.html');
const sel = html.match(/<select id="country-code"[^>]*>([\s\S]*?)<\/select>/);
if (!sel) throw new Error('listing.html: #country-code select not found');
const options = sel[1].split('\n').map(l => l.trim()).filter(l => l.startsWith('<option')).join('');
if (!options.includes('value="+1" selected')) throw new Error('listing.html: +1 (US) default option missing');

// ── 4. Assemble ──
let out = read('tools/lead-gate.template.js');
const sub = (marker, value) => {
    if (!out.includes(marker)) throw new Error(`template: ${marker} placeholder missing`);
    out = out.replace(marker, () => value);
};
sub('__I18N_JSON__', JSON.stringify(strings));
sub('__CSS__', JSON.stringify(fullCss));
sub('__CC_OPTIONS__', JSON.stringify(options));
out = `/* GENERATED by tools/build-lead-gate.js — do not edit; edit the template / i18n.js / listing.css instead. */\n` + out;

fs.writeFileSync(path.join(ROOT, 'lead-gate.js'), out);
console.log(`lead-gate.js written: ${out.length.toLocaleString()} bytes, ${KEYS.length} i18n keys, ${options.split('<option').length - 1} country codes`);
